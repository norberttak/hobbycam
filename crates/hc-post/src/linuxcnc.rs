//! LinuxCNC dialect: one self-contained program per tool segment, manual tool change between files.

use crate::{fmt_num, Job, PostProcessor};
use hc_project::{to_display, Units, WorkOrigin};
use hc_toolpath::{Move, Point3};

pub struct LinuxCnc;

/// `(`→`[`, `)`→`]`, control chars → space, non-ASCII → `?`, trimmed, max 60 chars, empty → `-`.
pub fn sanitize_comment(s: &str) -> String {
    let mapped: String = s
        .chars()
        .map(|c| match c {
            '(' => '[',
            ')' => ']',
            c if c.is_control() => ' ',
            c if !c.is_ascii() => '?',
            c => c,
        })
        .collect();
    // all ASCII now, so byte length = char count
    let mut out = mapped.trim().to_string();
    out.truncate(60);
    let out = out.trim_end();
    if out.is_empty() {
        "-".to_string()
    } else {
        out.to_string()
    }
}

/// On the written (formatted) values: same start and end (LinuxCNC would read a full circle), or a radius
/// r1 = |c − s| / r2 = |c − e| (c = s + (I, J)) below 10·10^-d, which LinuxCNC's centre-format check rejects.
fn degenerate_arc(s: [&str; 2], e: [&str; 2], ij: [&str; 2], decimals: usize) -> bool {
    if s == e {
        return true;
    }
    let v = |t: &str| t.parse::<f64>().unwrap_or(f64::NAN);
    let (sx, sy, ex, ey, i, j) = (v(s[0]), v(s[1]), v(e[0]), v(e[1]), v(ij[0]), v(ij[1]));
    let r1 = i.hypot(j);
    let r2 = (sx + i - ex).hypot(sy + j - ey);
    // 1e-9 relative slack so a radius of exactly 10·10^-d stays an arc despite float noise
    let min_r = 10f64.powi(1 - decimals as i32) * (1.0 - 1e-9);
    r1.is_nan() || r2.is_nan() || r1.min(r2) < min_r
}

/// Program writer state for one file.
struct Writer {
    out: String,
    units: Units,
    decimals: usize,
    /// Formatted F last written in this file.
    last_f: Option<String>,
}

impl Writer {
    fn num(&self, mm: f64) -> String {
        fmt_num(to_display(mm, self.units), self.decimals)
    }

    fn line(&mut self, s: &str) {
        self.out.push_str(s);
        self.out.push('\n');
    }

    /// " F<feed>" when it differs from the last F written, else "".
    fn feed(&mut self, feed: f64) -> String {
        let f = self.num(feed);
        if self.last_f.as_deref() == Some(f.as_str()) {
            return String::new();
        }
        let word = format!(" F{f}");
        self.last_f = Some(f);
        word
    }

    fn xyz(&self, p: &Point3) -> String {
        format!("X{} Y{} Z{}", self.num(p.x), self.num(p.y), self.num(p.z))
    }
}

impl PostProcessor for LinuxCnc {
    fn extension(&self) -> &'static str {
        "ngc"
    }

    fn program(&self, job: &Job) -> String {
        let inch = job.units == Units::Inch;
        let mut w = Writer {
            out: String::new(),
            units: job.units,
            decimals: if inch { 4 } else { 3 },
            last_f: None,
        };
        let tool = format!("T{} {}", job.tool, sanitize_comment(&job.tool_name));
        let origin = match job.origin {
            WorkOrigin::DrawingOrigin => "drawing origin".to_string(),
            WorkOrigin::StockBottomLeft => "stock bottom left".to_string(),
            WorkOrigin::StockCenter => "stock center".to_string(),
            WorkOrigin::Point(p) => format!("drawing point X{} Y{}", w.num(p.x), w.num(p.y)),
        };
        w.line(&format!(
            "({} - file {} of {})",
            sanitize_comment(&job.name),
            job.index,
            job.count
        ));
        w.line("(Generated by HobbyCAM, LinuxCNC post)");
        w.line(&format!(
            "(Units: {}. Z0 = top of stock. XY0 = {origin})",
            if inch { "inch" } else { "mm" }
        ));
        w.line(&format!("(Tool: {tool})"));
        for op in &job.ops {
            w.line(&format!("(Op: {})", sanitize_comment(&op.name)));
        }
        w.line(&format!(
            "(Before running: load {tool} and set Z0 on top of stock)"
        ));
        w.line(&format!(
            "G17 {} G40 G49 G80 G90 G91.1 G94 G98",
            if inch { "G20" } else { "G21" }
        ));
        w.line(if inch { "G64 P0.0004" } else { "G64 P0.01" });
        w.line(&format!("G0 Z{}", w.num(job.safe_z)));

        // fallback start if a job does not begin with a Rapid (export() guarantees it does)
        let mut cur = Point3 {
            x: 0.0,
            y: 0.0,
            z: job.safe_z,
        };
        let spin = |w: &mut Writer, rpm: u32| {
            w.line(&format!("S{rpm} M3"));
            w.line("G4 P2"); // hobby spindles have no at-speed signal
        };
        let mut rpm = job.ops.first().map(|op| op.rpm);
        if let Some(r) = rpm {
            spin(&mut w, r);
        }
        for op in &job.ops {
            w.line(&format!("({})", sanitize_comment(&op.name)));
            if rpm != Some(op.rpm) {
                spin(&mut w, op.rpm);
                rpm = Some(op.rpm);
            }
            let mut in_cycle = false;
            for mv in &op.moves {
                if in_cycle && !matches!(mv, Move::Drill { .. }) {
                    w.line("G80");
                    in_cycle = false;
                }
                match mv {
                    Move::Rapid(p) => {
                        let s = format!("G0 {}", w.xyz(p));
                        w.line(&s);
                        cur = *p;
                    }
                    Move::Linear { to, feed } => {
                        let s = format!("G1 {}{}", w.xyz(to), w.feed(*feed));
                        w.line(&s);
                        cur = *to;
                    }
                    Move::Arc {
                        to,
                        center,
                        ccw,
                        feed,
                    } => {
                        let (i, j) = (w.num(center.x - cur.x), w.num(center.y - cur.y));
                        let s = if degenerate_arc(
                            [&w.num(cur.x), &w.num(cur.y)],
                            [&w.num(to.x), &w.num(to.y)],
                            [&i, &j],
                            w.decimals,
                        ) {
                            format!("G1 {}{}", w.xyz(to), w.feed(*feed))
                        } else {
                            format!(
                                "{} {} I{i} J{j}{}",
                                if *ccw { "G3" } else { "G2" },
                                w.xyz(to),
                                w.feed(*feed)
                            )
                        };
                        w.line(&s);
                        cur = *to;
                    }
                    Move::Drill {
                        at,
                        z_bottom,
                        peck,
                        r_plane,
                        feed,
                    } => {
                        let (g, q) = match peck {
                            Some(q) => ("G83", format!(" Q{}", w.num(*q))),
                            None => ("G81", String::new()),
                        };
                        let s = format!(
                            "{g} X{} Y{} Z{} R{}{q}{}",
                            w.num(at.x),
                            w.num(at.y),
                            w.num(*z_bottom),
                            w.num(*r_plane),
                            w.feed(*feed)
                        );
                        w.line(&s);
                        // G98: back to the Z before the cycle
                        cur = Point3 {
                            x: at.x,
                            y: at.y,
                            z: cur.z,
                        };
                        in_cycle = true;
                    }
                }
            }
            if in_cycle {
                w.line("G80");
            }
        }
        w.line(&format!("G0 Z{}", w.num(job.tool_change_z)));
        w.line("M5");
        w.line("M2");
        w.out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn degenerate_arc_rules() {
        assert!(degenerate_arc(["1", "2"], ["1", "2"], ["5", "0"], 3));
        assert!(degenerate_arc(
            ["0", "0"],
            ["0.004", "0.004"],
            ["0", "0.004"],
            3
        ));
        assert!(!degenerate_arc(
            ["0", "0"],
            ["0.02", "0.02"],
            ["0", "0.02"],
            3
        ));
        // exactly 0.01 mm stays an arc, inch threshold is 0.001
        assert!(!degenerate_arc(
            ["0", "0"],
            ["0.01", "0.01"],
            ["0", "0.01"],
            3
        ));
        assert!(degenerate_arc(["0", "0"], ["0.0001", "0"], ["0", "0"], 4));
        assert!(!degenerate_arc(
            ["0", "0"],
            ["0.001", "0.001"],
            ["0", "0.001"],
            4
        ));
    }

    #[test]
    fn sanitize_rules() {
        assert_eq!(sanitize_comment("Slot (left) Ø6\tmm"), "Slot [left] ?6 mm");
        assert_eq!(sanitize_comment(&"x".repeat(100)).len(), 60);
        assert_eq!(sanitize_comment(""), "-");
        assert_eq!(sanitize_comment(" \t\n "), "-");
        assert_eq!(
            sanitize_comment(&format!("{} y", "x".repeat(59))),
            "x".repeat(59)
        );
    }
}
